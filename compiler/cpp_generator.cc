// ── Helpers ───────────────────────────────────────────────────────────────────

std::string ProtoBaseName(const std::string& filename) {
    auto dot = filename.rfind('.');
    return dot == std::string::npos ? filename : filename.substr(0, dot);
}

std::string PackageToNamespace(const std::string& package) {
    if (package.empty()) return {};
    std::string ns;
    for (char c : package) {
        ns += (c == '.') ? ':' : c;
        if (c == '.') ns += ':';
    }
    return ns;
}

std::string MethodPath(const MethodDescriptor* m) {
    return "/" + m->service()->full_name() + "/" + m->name();
}

static std::string FullCppType(const google::protobuf::Descriptor* d) {
    // Convert proto full_name to C++ scoped name (handles nested types).
    std::string full = d->full_name();
    // Replace dots with "::" and prepend "::"
    std::string result = "::";
    for (char c : full) {
        result += (c == '.') ? ':' : c;
        if (c == '.') result += ':';
    }
    return result;
}


// ── CppGenerator::Generate ────────────────────────────────────────────────────

bool CppGenerator::Generate(const FileDescriptor* file,
                             const std::string&    /*parameter*/,
                             GeneratorContext*      context,
                             std::string*           error) const
{
    if (file->service_count() == 0) return true;  // nothing to generate

    std::string base = ProtoBaseName(file->name());

    auto write_to_stream = [&](const std::string& content,
                                const std::string& filename) -> bool {
        std::unique_ptr<google::protobuf::io::ZeroCopyOutputStream> stream(
            context->Open(filename));
        const char* src       = content.data();
        std::size_t remaining = content.size();
        while (remaining > 0) {
            void* buf;
            int   buf_size;
            if (!stream->Next(&buf, &buf_size)) return false;
            auto n = std::min<std::size_t>(remaining, static_cast<std::size_t>(buf_size));
            std::memcpy(buf, src, n);
            if (static_cast<std::size_t>(buf_size) > n)
                stream->BackUp(static_cast<int>(buf_size) - static_cast<int>(n));
            src       += n;
            remaining -= n;
        }
        return true;
    };

    // Header
    {
        GeneratedHeader hdr;
        if (!GenerateHeader(file, hdr, error)) return false;
        if (!write_to_stream(hdr.content, base + ".rpcpio.pb.h")) return false;
    }

    // Source
    {
        GeneratedSource src_out;
        if (!GenerateSource(file, src_out, error)) return false;
        if (!write_to_stream(src_out.content, base + ".rpcpio.pb.cc")) return false;
    }

    return true;
}

